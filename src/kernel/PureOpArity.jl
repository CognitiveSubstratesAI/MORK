# PureOpArity.jl — VENDORED from upstream `kernel/src/pure.rs`. Two tables:
#   PURE_OP_ARITY  — the arities each `op!` arm's generated check ACCEPTS
#   PURE_REGISTER  — the names `pub fn register(scope)` actually registers, in source order
#
# 🔴 WHY BOTH ARE DATA AND NOT COMMENTS.
#
# ARITY: every arm hard-codes a check we dropped when we ported the arm's expression instead of the
# arm (`if items != 1 { return Err(...) }`, pure.rs:64-74). The constant lives in the macro
# INVOCATION's class keyword — Rust source we do not carry at runtime — so it is extracted once and
# vendored, exactly as `test/conformance/PORT_INVENTORY.txt` vendors the symbol list.
#
# REGISTER: `pure.rs:910-1300` is `pub fn register`, ~370 explicit `scope.add_func(name, fn,
# FuncType::Pure)` calls, and it was NOT ported — we inferred the registration set from our own
# `PURE_OPS` keys. Inferring it means the registry can never disagree with itself, so it can never
# report a missing op. Driving registration from THIS list makes a gap loud.
# Verified while extracting: every registration uses the function's own name (NO aliases), and every
# one is `FuncType::Pure` — NONE are Macro, including `ifnz`.
#
# ⚠️ `//` COMMENTS ARE STRIPPED BEFORE MATCHING. The file carries a commented-out template line,
# `// scope.add_func("$1", $1, FuncType::Pure);`, and matching it produced a bogus `"$1"` op — which
# in Julia is a string interpolation and a hard ParseError. `rust_symbols` in tools/port_inventory.jl
# deletes the same artifact for the same reason.
#
# `nothing` arity means the arm emits NO check: `nary` folds any count by construction and `tuple`
# deliberately takes N. It does NOT mean "unknown".
#
# `ifnz` is [3, 5] — upstream `if items != 3 && items != 5` (pure.rs:877), the with/without-else shapes.
#
# ⚠️ FAITHFUL TO AN UPSTREAM BUG: the `quaternary` arm checks `items != 3` then consumes FOUR operands
# (pure.rs:25-38), so every `*_ternarylogic` op is unreachable upstream. We record 3 to match the
# CHECK. Do not "fix" this to 4 without deciding to diverge deliberately.
#
# Regenerate when upstream's op table changes; review the diff.


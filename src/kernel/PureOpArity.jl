# PURE_OP_OPERAND_WIDTHS / PURE_OP_NARY_WIDTH — VENDORED from the `op!` INVOCATIONS in pure.rs
# =====================================================================
#
# 🔴 THE THIRD DROPPED CHECK. `op_skeleton` restored the arm's ARITY check; this restores its
# OPERAND WIDTH check. Every arm reads its operands with `expr.consume::<$tx>()`, and
# `consume::<T>` (eval-ffi/src/source.rs:152) is EXACT:
#
#     fn check(e) -> bool { *e.ptr == item_byte(Tag::SymbolSize(size_of::<Self>())) }
#
# The operand must be a symbol of PRECISELY `size_of::<T>()` bytes. Anything else is
# `Err("failed to consume <T>")` and the atom is skipped — it is not coerced, padded or truncated.
#
# ⚠️ MEASURED DIVERGENCE THAT MOTIVATED THIS (2026-07-31), ours vs the release binary on one probe:
#
#     (lt_i64 aaaaaaaa bbbbbbbb)      8+8   upstream (ok ^A)   ours (ok \x01)     agree
#     (lt_i64 aaaa bbbbbbbb)          4+8   upstream ABSENT    ours ABSENT         agree
#     (lt_i64 aaaaaaaaaaaa bbbb…)   12+12   upstream ABSENT    ours (long \x01)   DIVERGE
#
# We rejected TOO SHORT (the body ran out of bytes) but ACCEPTED TOO LONG, emitting a result where
# upstream skips the atom. Silent, and it would have applied to every typed op.
#
# WHY VENDORED. The types live in the macro INVOCATION (`op!(num binary u8_nand(x: u8, y: u8) => …)`)
# — Rust source we do not carry at runtime — exactly like the arities above.
#
# NARY IS DIFFERENT AND IS SEPARATE FOR THAT REASON. Its arm is
# `($initial, $t: $tt, $x: $tx)` and the loop is `for _ in 0..items { consume::<$tx>() }`, so the
# accumulator type `$tt` is NOT an operand width — EVERY element is read as `$tx`, the LAST declared
# type. Reading the first pair instead would have given the wrong width for all 43.

# PureOpArity.jl — VENDORED arity table, generated from upstream `kernel/src/pure.rs`.
#
# 🔴 WHY THIS IS DATA AND NOT A COMMENT. Every `op!` arm hard-codes an arity check that we
# dropped when we ported the arm's expression instead of the arm (`if items != 1 { return
# Err(...) }`, pure.rs:64-74 etc). The constant is in the macro INVOCATION's class keyword, which
# is Rust source we do not carry at runtime — so it is extracted once and vendored here, exactly
# as `test/conformance/PORT_INVENTORY.txt` vendors the upstream symbol list.
#
# `nothing` means the arm emits NO check: the `nary` fold accepts any count by construction, and
# `tuple` deliberately takes N. It does NOT mean 'unknown'.
#
# ⚠️ FAITHFUL TO AN UPSTREAM BUG: the `quaternary` arm checks `items != 3` and then consumes FOUR
# operands (pure.rs:25-38), so every `*_ternarylogic` op is unreachable upstream — a 3-arg call
# reads a fourth operand that was never supplied, and a 4-arg call is rejected. We record 3 to
# match the CHECK. Do not 'fix' this to 4 without deciding to diverge deliberately.
#
# Regenerate when upstream's op table changes; review the diff.

